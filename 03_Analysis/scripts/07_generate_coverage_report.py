# メッシュコードを抽出
pref_count = defaultdict(int)
mesh_codes = []

for f in zip_files:
    basename = os.path.basename(f)
    match = re.search(r'_(\d{4})', basename)
    if match:
        mesh_code = match.group(1)
        mesh_codes.append(mesh_code)
        
        if mesh_code in MESH_TO_PREF:
            pref_code = MESH_TO_PREF[mesh_code]
            pref_count[pref_code] += 1

# ファイルに出力
with open(output_file, 'w', encoding='utf-8') as f:
    f.write(f"Total files: {len(zip_files)}\n\n")
    
    f.write("=== 都道府県別ファイル数 ===\n")
    for pref_code in sorted(pref_count.keys()):
        pref_name = PREF_NAMES.get(pref_code, f"不明({pref_code})")
        count = pref_count[pref_code]
        f.write(f"{pref_code:2d}. {pref_name:10s}: {count:3d}ファイル\n")
    
    f.write(f"\n=== カバーされている都道府県数 ===\n")
    f.write(f"合計: {len(pref_count)} / 47都道府県\n")
    
    f.write(f"\n=== カバーされていない都道府県 ===\n")
    all_prefs = set(range(1, 48))
    covered_prefs = set(pref_count.keys())
    missing_prefs = all_prefs - covered_prefs
    
    if missing_prefs:
        for pref_code in sorted(missing_prefs):
            pref_name = PREF_NAMES.get(pref_code, f"都道府県{pref_code}")
            f.write(f"{pref_code:2d}. {pref_name}\n")
    else:
        f.write("全都道府県がカバーされています!\n")
    
    f.write(f"\n=== メッシュコード範囲 ===\n")
    f.write(f"最小: {min(mesh_codes)}\n")
    f.write(f"最大: {max(mesh_codes)}\n")
    f.write(f"ユニーク数: {len(set(mesh_codes))}\n")

print(f"Report saved to: {output_file}")
print(f"Covered prefectures: {len(pref_count)} / 47")
